"""
agentops.span
=============
``SpanContext`` — a context-manager (sync and async) that records a single
sub-operation within a parent :class:`~agentops.context.TraceContext`.

Typical usage
-------------
Used directly via :meth:`~agentops.context.TraceContext.add_span`:

>>> with ctx.add_span("call-llm", span_type="llm") as span:
...     span.set_input("Translate 'hello' to French")
...     response = llm.call(prompt)
...     span.set_output(response)
...     span.set_model("gpt-4o", tokens_input=20, tokens_output=10)

Or via the ``@agentops.span`` decorator (see :mod:`agentops.decorators`).
"""

from __future__ import annotations

import logging
import time
from datetime import datetime, timezone
from typing import TYPE_CHECKING, Any, Optional

from .client import AgentOpsClient
from .models import SpanData

if TYPE_CHECKING:
    # Avoid circular import at runtime; TraceContext is only used for type hints.
    from .context import TraceContext

logger = logging.getLogger(__name__)


class SpanContext:
    """
    Records one discrete operation within a trace.

    Parameters
    ----------
    trace_ctx:
        The parent :class:`~agentops.context.TraceContext`.
    span_id:
        UUID string for this span (generated by the parent context).
    name:
        Human-readable label for this span.
    span_type:
        Category string.  Recommended values: ``"llm"``, ``"tool"``,
        ``"retrieval"``, ``"chain"``, ``"custom"``.
    parent_span_id:
        UUID of the enclosing span, or ``None`` for top-level spans.

    Attributes
    ----------
    span_id : str
        UUID string identifying this span.
    name : str
        Human-readable label.
    span_type : str
        Span category.

    Thread/async safety
    -------------------
    ``SpanContext`` is **not** shared across threads or tasks.  Each concurrent
    unit of work should use its own ``TraceContext`` and ``SpanContext``.
    """

    def __init__(
        self,
        trace_ctx: "TraceContext",
        span_id: str,
        name: str,
        span_type: str,
        parent_span_id: Optional[str] = None,
    ) -> None:
        self._trace_ctx = trace_ctx
        self.span_id = span_id
        self.name = name
        self.span_type = span_type
        self._parent_span_id = parent_span_id

        # Timing
        self._started_at: Optional[datetime] = None
        self._ended_at: Optional[datetime] = None

        # I/O
        self._input_text: Optional[str] = None
        self._output_text: Optional[str] = None

        # LLM fields
        self._model: Optional[str] = None
        self._tokens_input: Optional[int] = None
        self._tokens_output: Optional[int] = None
        self._cost_usd: Optional[float] = None

        # Status
        self._status: str = "ok"
        self._error_message: Optional[str] = None
        self._error_type: Optional[str] = None

        # Arbitrary metadata
        self._metadata: dict = {}

    # ------------------------------------------------------------------
    # Fluent setters
    # ------------------------------------------------------------------

    def set_input(self, text: str) -> "SpanContext":
        """
        Record the text input to this span.

        Parameters
        ----------
        text:
            The input string (prompt, query, raw data, etc.).

        Returns
        -------
        SpanContext
            Returns ``self`` to allow method chaining.
        """
        self._input_text = text
        return self

    def set_output(self, text: str) -> "SpanContext":
        """
        Record the text output from this span.

        Parameters
        ----------
        text:
            The output string (completion, search results, transformed data, etc.).

        Returns
        -------
        SpanContext
            Returns ``self`` to allow method chaining.
        """
        self._output_text = text
        return self

    def set_model(
        self,
        model: str,
        tokens_input: int,
        tokens_output: int,
    ) -> "SpanContext":
        """
        Record LLM model usage and automatically calculate estimated cost.

        Cost is estimated from the built-in pricing table in
        :class:`~agentops.client.AgentOpsClient`.  If the model is not in the
        table, ``cost_usd`` is left as ``None``.

        Parameters
        ----------
        model:
            Model identifier (e.g. ``"gpt-4o"``, ``"claude-3-5-sonnet"``).
        tokens_input:
            Number of prompt/input tokens.
        tokens_output:
            Number of completion/output tokens.

        Returns
        -------
        SpanContext
            Returns ``self`` to allow method chaining.

        Example
        -------
        >>> span.set_model("gpt-4o", tokens_input=800, tokens_output=200)
        """
        if tokens_input < 0:
            raise ValueError(f"tokens_input must be >= 0; got {tokens_input}")
        if tokens_output < 0:
            raise ValueError(f"tokens_output must be >= 0; got {tokens_output}")

        self._model = model
        self._tokens_input = tokens_input
        self._tokens_output = tokens_output
        self._cost_usd = AgentOpsClient.calculate_cost(model, tokens_input, tokens_output)
        return self

    def set_metadata(self, key: str, value: Any) -> "SpanContext":
        """
        Attach an arbitrary key-value pair to this span.

        Parameters
        ----------
        key:
            Metadata key (string).
        value:
            Any JSON-serialisable value.

        Returns
        -------
        SpanContext
            Returns ``self`` to allow method chaining.
        """
        if not isinstance(key, str):
            raise TypeError(f"Metadata key must be a str; got {type(key).__name__}")
        self._metadata[key] = value
        return self

    # ------------------------------------------------------------------
    # Synchronous context manager
    # ------------------------------------------------------------------

    def __enter__(self) -> "SpanContext":
        """Start timing the span."""
        self._started_at = datetime.now(tz=timezone.utc)
        logger.debug("Span '%s' (%s) started.", self.name, self.span_id)
        return self

    def __exit__(
        self,
        exc_type: Optional[type],
        exc_val: Optional[BaseException],
        exc_tb: Any,
    ) -> bool:
        """
        Stop timing, capture any exception, finalise the span, and register it
        with the parent trace context.

        Returns False so exceptions propagate normally.
        """
        self._ended_at = datetime.now(tz=timezone.utc)
        self._finalise(exc_type, exc_val)
        # Register this span with the parent trace so it's included when the
        # trace is serialised and sent.
        self._trace_ctx._register_span(self)
        logger.debug(
            "Span '%s' (%s) ended; status=%s duration_ms=%.1f",
            self.name,
            self.span_id,
            self._status,
            self._duration_ms() or 0,
        )
        return False  # do not suppress exceptions

    # ------------------------------------------------------------------
    # Asynchronous context manager
    # ------------------------------------------------------------------

    async def __aenter__(self) -> "SpanContext":
        """Async version of ``__enter__``."""
        return self.__enter__()

    async def __aexit__(
        self,
        exc_type: Optional[type],
        exc_val: Optional[BaseException],
        exc_tb: Any,
    ) -> bool:
        """Async version of ``__exit__``."""
        return self.__exit__(exc_type, exc_val, exc_tb)

    # ------------------------------------------------------------------
    # Serialisation
    # ------------------------------------------------------------------

    def to_model(self) -> SpanData:
        """
        Serialise this span into a :class:`~agentops.models.SpanData` Pydantic model
        ready for JSON encoding and transmission.

        Returns
        -------
        SpanData
            The wire-format representation of this span.
        """
        return SpanData(
            span_id=self.span_id,
            trace_id=self._trace_ctx.trace_id,
            parent_span_id=self._parent_span_id,
            name=self.name,
            span_type=self.span_type,
            started_at=self._started_at or datetime.now(tz=timezone.utc),
            ended_at=self._ended_at,
            duration_ms=self._duration_ms(),
            input_text=self._input_text,
            output_text=self._output_text,
            model=self._model,
            tokens_input=self._tokens_input,
            tokens_output=self._tokens_output,
            cost_usd=self._cost_usd,
            status=self._status,
            error_message=self._error_message,
            error_type=self._error_type,
            metadata=self._metadata,
        )

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    def _finalise(
        self,
        exc_type: Optional[type],
        exc_val: Optional[BaseException],
    ) -> None:
        """Set status and capture error info if an exception occurred."""
        if exc_type is not None:
            self._status = "error"
            self._error_type = f"{exc_type.__module__}.{exc_type.__qualname__}"
            self._error_message = str(exc_val)
            logger.debug(
                "Span '%s' captured exception: %s: %s",
                self.name,
                self._error_type,
                self._error_message,
            )

    def _duration_ms(self) -> Optional[float]:
        """Calculate elapsed time in milliseconds, or None if the span is still open."""
        if self._started_at is None or self._ended_at is None:
            return None
        delta = self._ended_at - self._started_at
        return delta.total_seconds() * 1000
